#!/bin/bash

echo "🔄 Перезапуск сервисов с оптимизированными настройками для больших файлов..."

# Останавливаем все сервисы
echo "⏹️  Останавливаем сервисы..."
docker-compose down

# Очищаем кэш Redis
echo "🧹 Очищаем кэш Redis..."
docker run --rm -v redis_data:/data redis:alpine redis-cli -h redis FLUSHALL || echo "Redis не запущен, пропускаем очистку"

# Очищаем временные файлы
echo "🧹 Очищаем временные файлы..."
rm -rf media/temp/* 2>/dev/null || true
mkdir -p media/temp

# Очищаем процессы Chrome
echo "🧹 Очищаем процессы Chrome..."
pkill -f chrome || true
pkill -f chromedriver || true

# Пересобираем контейнеры с новыми настройками
echo "🔨 Пересобираем контейнеры..."
docker-compose build --no-cache backend

# Запускаем сервисы
echo "🚀 Запускаем сервисы с оптимизированными настройками..."
docker-compose up -d

# Ждем запуска сервисов
echo "⏳ Ждем запуска сервисов..."
sleep 10

# Проверяем статус
echo "📊 Статус сервисов:"
docker-compose ps

echo "✅ Оптимизация завершена!"
echo ""
echo "📈 Основные улучшения:"
echo "• Уменьшены таймауты Selenium с 5 до 3 секунд"
echo "• Уменьшены таймауты HTTP запросов с 30 до 10 секунд"
echo "• Уменьшено количество повторных попыток"
echo "• Увеличены лимиты времени Celery до 100 часов"
echo "• Добавлено разбиение больших файлов на части"
echo "• Уменьшен размер батча с 50 до 25 строк"
echo "• Увеличено количество воркеров Celery до 2"
echo ""
echo "🎯 Теперь парсер должен обрабатывать файлы с 250-300 артикулами без превышения таймаута!"
